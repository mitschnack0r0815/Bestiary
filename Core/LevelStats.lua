ns.MAX_LEVEL = 63

-- NPC classes the table knows; rogues use the warrior rows, unknown mobs too (most beasts are
-- warriors to the game). Player classes (your own card) by how they fight.
local CLASS_ROWS = { WARRIOR = "WARRIOR", ROGUE = "WARRIOR", PALADIN = "PALADIN", MAGE = "MAGE",
	HUNTER = "PALADIN", SHAMAN = "PALADIN", DRUID = "PALADIN", PRIEST = "MAGE", WARLOCK = "MAGE" }

local function Row(level, class)
	local rows = BASE[CLASS_ROWS[class or ""] or "WARRIOR"]
	level = math.max(1, math.min(ns.MAX_LEVEL, math.floor((level or 1) + 0.5)))
	return rows[level]
end

function ns.BaseHealth(level, class)
	return Row(level, class)[1]
end

-- A typical melee hit of a mob of this level and class: (base damage + attack power / 14) times
-- its attack time, as cMaNGOS builds it (github.com/cmangos/issues/wiki/creature_template)
ns.ATTACK_SPEED = 2 -- seconds, when a mob's own attack speed isn't known
function ns.BaseHit(level, class, attackSpeed)
	local row = Row(level, class)
	return (row[2] + row[3] / 14) * (attackSpeed or ns.ATTACK_SPEED)
end

function ns.BaseArmor(level, class)
	return Row(level, class)[4]
end

-- Classic armor: physical damage reduced by armor / (armor + 400 + 85 * attacker level), at
-- most 75%; from level 60 the constant is 467.5 * level - 22167.5
function ns.ArmorReduction(armor, level)
	if not armor or armor <= 0 then
		return 0
	end
	local constant = level >= 60 and (467.5 * level - 22167.5) or (400 + 85 * level)
	return math.min(0.75, armor / (armor + constant))
end
